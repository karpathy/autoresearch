_CURRENT_OPERATION: ContextVar[str | None] = ContextVar("autoresearch_operation_id", default=None)
_OPERATION_KINDS = {"baseline", "trial", "resume", "recover", "epoch", "probe", "replay"}
_SAFE_PROVIDER = re.compile(r"^[A-Za-z0-9_.:/-]{1,128}$")


class OperationCancellationRequested(LabError):
    code = "operation_cancelled"

    def __init__(self):
        super().__init__("Operation cancelled by request", code=self.code)


def safe_operation_context(config: LabConfig) -> dict[str, Any]:
    """Return only non-secret measurement settings needed to bind a worker request."""
    capabilities = getattr(config, "evaluator_capabilities", {}) or {}
    if not isinstance(capabilities, dict):
        raise LabError("Evaluator provider capabilities must be an object", code="E_PROVIDER_CONFIG")
    provider = capabilities.get("provider")
    if provider is not None and (not isinstance(provider, str) or not _SAFE_PROVIDER.fullmatch(provider)):
        raise LabError("Evaluator provider identity is invalid", code="E_PROVIDER_CONFIG")
    guards = []
    for name, direction in getattr(config, "guards", ()):
        if (not isinstance(name, str) or not _SAFE_PROVIDER.fullmatch(name)
                or direction not in {"min", "max"}):
            raise LabError("Evaluator metric configuration is invalid", code="E_PROVIDER_CONFIG")
        guards.append({"name": name, "direction": direction})
    primary = getattr(config, "primary", None)
    direction = getattr(config, "direction", None)
    repeats = getattr(config, "repeats", None)
    if (not isinstance(primary, str) or not _SAFE_PROVIDER.fullmatch(primary)
            or direction not in {"min", "max"} or isinstance(repeats, bool)
            or not isinstance(repeats, int) or repeats < 1):
        raise LabError("Evaluator measurement configuration is invalid", code="E_PROVIDER_CONFIG")
    state = SQLiteStore().load_state(config.lab_id)
    epoch_id = state.get("current_epoch")
    if isinstance(epoch_id, bool) or not isinstance(epoch_id, int) or epoch_id < 1:
        raise LabError("SQLite lab has no current contract epoch", code="E_PROVIDER_CONFIG")
    return {
        "schema": 1,
        "epoch_id": epoch_id,
        "provider": provider,
        "primary": primary,
        "direction": direction,
        "guards": guards,
        "repeats": repeats,
    }


def _bind_operation_context(config: LabConfig, kind: str, payload: dict[str, Any]) -> dict[str, Any]:
    prepared = {**payload}
    params = dict(payload["params"])
    if "harness_policy" in params:
        raise LabError("Harness policy snapshots are generated by the host and cannot be supplied by callers",
                       code="E_HARNESS_POLICY_INVALID")
    confirmed = params.pop("confirmed", None)
    if kind == "probe":
        env = params.get("env")
        repeats = params.get("repeats")
        if (not isinstance(params.get("commit"), str) or not params["commit"].strip()
                or not isinstance(params.get("group"), str) or not params["group"].strip()
                or not isinstance(params.get("label"), str) or not params["label"].strip()
                or not isinstance(env, dict)
                or any(not isinstance(key, str) or not isinstance(value, str) for key, value in env.items())
                or isinstance(repeats, bool) or not isinstance(repeats, int) or repeats < 1):
            raise LabError("Probe operation payload is invalid", code="E_CONTRACT_PROBE")
    if kind == "replay":
        trial_id = params.get("trial_id")
        if not isinstance(trial_id, str) or not trial_id.startswith("trial-"):
            raise LabError("Replay operation requires a trial id", code="E_CONTRACT_REPLAY")
    policy = authorize_operation(config, kind, confirmed=confirmed)
    context = safe_operation_context(config)
    if kind == "trial":
        from .trial import validate_trial_request
        params["hypothesis"] = validate_trial_request(config, params.get("hypothesis"))
    supplied = params.get("operation_context")
    if supplied is not None and supplied != context:
        raise LabError("Operation context does not match the current lab configuration", code="E_PROVIDER_CONFIG")
    params["operation_context"] = context
    params["harness_policy"] = policy
    prepared["command"] = kind
    prepared["params"] = params
    return prepared


def _config_for(config_or_ref: LabConfig | str) -> LabConfig:
    if isinstance(config_or_ref, LabConfig):
        config = config_or_ref
    else:
        store = SQLiteStore()
        try:
            row = store.get_lab(config_or_ref)
        except EntityNotFoundError as error:
            raise LabError(f"Unknown SQLite lab: {config_or_ref}") from error
        config = load_config(row["config_path"], allow_pending=True)
    if config.storage_mode != "sqlite" or not config.lab_id:
        raise LabError("Durable operations require a SQLite-backed lab")
    return config


def _validate_request(kind: str, idempotency_key: str, payload: dict[str, Any]) -> None:
    if kind not in _OPERATION_KINDS:
        raise LabError(f"Unsupported operation kind: {kind}")
    if not isinstance(idempotency_key, str) or not idempotency_key.strip() or len(idempotency_key) > 256:
        raise LabError("Operation idempotency key must be 1–256 characters")
    if not isinstance(payload, dict) or payload.get("command") != kind or not isinstance(payload.get("params"), dict):
        raise LabError("Operation payload must contain matching command and params")
    if len(json.dumps(payload, ensure_ascii=False, separators=(",", ":")).encode("utf-8")) > 65536:
        raise LabError("Operation payload exceeds the 64 KiB limit")


def _reconcile_active(store: SQLiteStore, active: dict[str, Any], *, explicit_recover: bool) -> None:
    status = active["status"]
    pid = int(active.get("pid") or 0)
    if pid and _pid_alive(pid):
        raise LabError(
            f"Operation {active['operation_id']} is still owned by live pid {pid}",
            code="operation_already_active",
        )
    if status in {"queued", "running", "finalizing"}:
        store.transition_operation(
            active["operation_id"], status, "recovery_required",
            error={
                "code": "worker_lost",
                "message": "The operation worker stopped before recording a terminal result; its outcome is uncertain",
            },
        )
        status = "recovery_required"
    if status == "recovery_required" and explicit_recover:
        store.transition_operation(
            active["operation_id"], "recovery_required", "failed",
            error={"code": "reconciled_by_explicit_recover"},
        )


def _enqueue_locked(
    store: SQLiteStore,
    config: LabConfig,
    kind: str,
    idempotency_key: str,
    payload: dict[str, Any],
) -> dict[str, Any]:
    try:
        return store.enqueue_operation(config.lab_id, kind, idempotency_key, payload)
    except ActiveOperationError:
        active = store.load_worker(config.lab_id)
        if not active or active.get("status") not in {"queued", "running", "finalizing", "recovery_required"}:
            raise
        _reconcile_active(store, active, explicit_recover=kind == "recover")
        if kind != "recover":
            raise LabError(
                "A previous operation has an unknown outcome; run explicit recover before retrying",
                code="operation_already_active",
            )
        return store.enqueue_operation(config.lab_id, kind, idempotency_key, payload)


def reserve_operation(
    config_or_ref: LabConfig | str,
    kind: str,
    idempotency_key: str,
    payload: dict[str, Any],
) -> dict[str, Any]:
    """Durably reserve one operation; callers that spawn should use reserve_and_launch_operation."""
    config = _config_for(config_or_ref)
    store = SQLiteStore()
    with lab_lock(config.state_dir):
        locked_config = _config_for(str(config.lab_id))
        if locked_config.state_dir != config.state_dir:
            raise LabError("SQLite lab state directory changed while reserving an operation")
        payload = _bind_operation_context(locked_config, kind, payload)
        _validate_request(kind, idempotency_key, payload)
        return _enqueue_locked(store, locked_config, kind, idempotency_key, payload)


def reserve_and_launch_operation(
    config_or_ref: LabConfig | str,
    kind: str,
    idempotency_key: str,
    payload: dict[str, Any],
    launcher: Callable[[str], Any],
) -> dict[str, Any]:
    """Reserve and spawn while holding the lab lock, closing the enqueue/spawn recovery race."""
    config = _config_for(config_or_ref)
    store = SQLiteStore()
    with lab_lock(config.state_dir):
        locked_config = _config_for(str(config.lab_id))
        if locked_config.state_dir != config.state_dir:
            raise LabError("SQLite lab state directory changed while reserving an operation")
        payload = _bind_operation_context(locked_config, kind, payload)
        _validate_request(kind, idempotency_key, payload)
        operation = _enqueue_locked(store, locked_config, kind, idempotency_key, payload)
        if operation.get("replayed"):
            return operation

        operation_id = operation["operation_id"]
        launch: Any = None
        try:
            launch = launcher(str(operation_id))
            if isinstance(launch, dict):
                pid = launch.get("pid")
                identity = launch.get("worker_identity")
                if (isinstance(pid, bool) or not isinstance(pid, int) or pid <= 0
                        or not isinstance(identity, dict)):
                    raise LabError("Worker launcher did not provide a verified process identity",
                                   code="worker_identity_unavailable")
                worker_job_handle = launch.get("worker_job_handle")
                if identity.get("kind") == "windows_job" and (
                    isinstance(worker_job_handle, bool) or not isinstance(worker_job_handle, int)
                    or worker_job_handle <= 0
                ):
                    raise LabError("Windows worker did not retain its Job Object handle",
                                   code="worker_identity_unavailable")
                store.record_operation_spawn(
                    operation_id, pid, worker_identity=identity,
                    worker_job_handle=worker_job_handle,
                )
                resume = launch.get("resume")
                if callable(resume):
                    resume()
            elif isinstance(launch, int) and not isinstance(launch, bool) and launch > 0:
                # Keep custom test and embedding launchers compatible; built-in launchers
                # return a PID plus a process identity before the lock is released.
                store.record_operation_spawn(operation_id, launch)
        except Exception as error:
            abort = launch.get("abort") if isinstance(launch, dict) else None
            if callable(abort):
                try:
                    abort()
                except Exception:
                    pass
            store.transition_operation(
                operation_id, "queued", "recovery_required",
                error={"code": "worker_spawn_uncertain", "message": str(error)[:400]},
            )
            operation = store.get_operation(operation_id)
            progress = operation.get("progress")
            if isinstance(progress, dict):
                operation["progress"] = {
                    key: value for key, value in progress.items()
                    if key not in {"worker_identity", "worker_job_handle"}
                }
            operation["spawn_error"] = str(error)[:400]
        return operation


def set_current_operation(operation_id: str | None):
    return _CURRENT_OPERATION.set(operation_id)


def reset_current_operation(token: Any) -> None:
    _CURRENT_OPERATION.reset(token)


def current_operation_id() -> str | None:
    return _CURRENT_OPERATION.get()


def require_durable_operation_context(config: LabConfig, executor: str) -> None:
    """Keep SQLite measurement executors reachable only through a claimed worker."""
    if getattr(config, "storage_mode", "legacy") != "sqlite":
        return
    operation_id = _CURRENT_OPERATION.get()
    if not operation_id:
        raise LabError(
            f"SQLite {executor} execution must be submitted through the durable operation service",
            code="E_DURABLE_OPERATION_REQUIRED",
        )
    try:
        operation = SQLiteStore().get_operation(operation_id)
    except EntityNotFoundError as error:
        raise LabError("Durable worker operation record is missing", code="E_DURABLE_OPERATION_REQUIRED") from error
    allowed_kinds = {
        "baseline": {"baseline", "resume"},
        "trial": {"trial", "resume"},
        "probe": {"probe"},
        "replay": {"replay"},
    }
    if (operation.get("kind") not in allowed_kinds.get(executor, set())
            or operation.get("status") not in {"running", "finalizing"}
            or str(operation.get("lab_id")) != str(config.lab_id)):
        raise LabError(
            "Durable worker context does not authorize this measurement executor",
            code="E_DURABLE_OPERATION_REQUIRED",
        )


def mark_operation_finalizing() -> None:
    operation_id = _CURRENT_OPERATION.get()
    if not operation_id:
        return
    store = SQLiteStore()
    operation = store.get_operation(operation_id)
    progress = operation.get("progress")
    if isinstance(progress, dict) and progress.get("cancel_requested") is True:
        raise OperationCancellationRequested()
    if operation["status"] == "running":
        store.transition_operation(operation_id, "running", "finalizing")


def _windows_kernel32() -> Any:
    return ctypes.WinDLL("kernel32", use_last_error=True)


def _windows_start_token(handle: Any) -> str | None:
    class FileTime(ctypes.Structure):
        _fields_ = [("low", ctypes.c_uint32), ("high", ctypes.c_uint32)]

    kernel = _windows_kernel32()
    get_times = kernel.GetProcessTimes
    get_times.argtypes = [ctypes.c_void_p] + [ctypes.POINTER(FileTime)] * 4
    get_times.restype = ctypes.c_int
    created, exited, kernel_time, user_time = FileTime(), FileTime(), FileTime(), FileTime()
    if not get_times(ctypes.c_void_p(int(handle)), ctypes.byref(created), ctypes.byref(exited),
                     ctypes.byref(kernel_time), ctypes.byref(user_time)):
        return None
    return f"{created.high:08x}{created.low:08x}"


def _linux_process_details(pid: int) -> tuple[str, int, int] | None:
    """Read boot/start identity and isolated process/session IDs from procfs."""
    try:
        stat = Path(f"/proc/{pid}/stat").read_text(encoding="ascii")
        close_paren = stat.rfind(")")
        fields = stat[close_paren + 2:].split()
        start_ticks, process_group, session_id = fields[19], int(fields[2]), int(fields[3])
        boot_id = Path("/proc/sys/kernel/random/boot_id").read_text(encoding="ascii").strip()
    except (OSError, IndexError, ValueError):
        return None
    return f"{boot_id}:{start_ticks}", process_group, session_id


def capture_worker_identity(process: Any, operation_id: str) -> tuple[dict[str, Any] | None, Any]:
    """Capture identity while the launcher still holds the lab lock and before Popen is reaped."""
    pid = int(getattr(process, "pid", 0) or 0)
    if pid <= 0:
        return None, None
    if os.name == "nt":
        process_handle = getattr(process, "_handle", None)
        if process_handle is None:
            return None, None
        start_token = _windows_start_token(process_handle)
        if not start_token:
            return None, None
        job_name = f"Local\\AutoResearch-{operation_id}"
        kernel = _windows_kernel32()
        create_job = kernel.CreateJobObjectW
        create_job.argtypes = [ctypes.c_void_p, ctypes.c_wchar_p]
        create_job.restype = ctypes.c_void_p
        job_handle = create_job(None, job_name)
        if not job_handle:
            return None, None
        if ctypes.get_last_error() == 183:  # ERROR_ALREADY_EXISTS: never attach to an old job.
            kernel.CloseHandle(job_handle)
            return None, None
        if not _set_job_kill_on_close(job_handle):
            kernel.CloseHandle(job_handle)
            return None, None
        assign = kernel.AssignProcessToJobObject
        assign.argtypes = [ctypes.c_void_p, ctypes.c_void_p]
        assign.restype = ctypes.c_int
        if not assign(job_handle, ctypes.c_void_p(int(process_handle))):
            kernel.CloseHandle(job_handle)
            return None, None
        return {"kind": "windows_job", "start_token": start_token, "job_name": job_name}, job_handle
    if sys.platform.startswith("linux"):
        details = _linux_process_details(pid)
        if details and details[1:] == (pid, pid):
            return {
                "kind": "linux_proc", "start_token": details[0],
                "process_group": pid, "session_id": pid,
            }, None
        return None, None
    try:
        pgid = os.getpgid(pid)
    except (AttributeError, OSError):
        pgid = pid
    try:
        sid = os.getsid(pid)
    except (AttributeError, OSError):
        sid = pid
    return {
        "kind": "posix_proc",
        "start_token": str(pid),
        "process_group": pgid,
        "session_id": sid,
    }, None


def close_worker_identity_resource(handle: Any) -> None:
    if os.name == "nt" and handle:
        _windows_kernel32().CloseHandle(ctypes.c_void_p(int(handle)))


def _set_job_kill_on_close(job_handle: Any) -> bool:
    """Make a worker-owned last handle close terminate any orphaned descendants."""
    class BasicLimitInformation(ctypes.Structure):
        _fields_ = [
            ("per_process_user_time_limit", ctypes.c_int64),
            ("per_job_user_time_limit", ctypes.c_int64),
            ("limit_flags", ctypes.c_uint32),
            ("minimum_working_set_size", ctypes.c_size_t),
            ("maximum_working_set_size", ctypes.c_size_t),
            ("active_process_limit", ctypes.c_uint32),
            ("affinity", ctypes.c_size_t),
            ("priority_class", ctypes.c_uint32),
            ("scheduling_class", ctypes.c_uint32),
        ]

    class IoCounters(ctypes.Structure):
        _fields_ = [(name, ctypes.c_uint64) for name in (
            "read_operation_count", "write_operation_count", "other_operation_count",
            "read_transfer_count", "write_transfer_count", "other_transfer_count",
        )]

    class ExtendedLimitInformation(ctypes.Structure):
        _fields_ = [
            ("basic_limit_information", BasicLimitInformation),
            ("io_info", IoCounters),
            ("process_memory_limit", ctypes.c_size_t),
            ("job_memory_limit", ctypes.c_size_t),
            ("peak_process_memory_used", ctypes.c_size_t),
            ("peak_job_memory_used", ctypes.c_size_t),
        ]

    try:
        info = ExtendedLimitInformation()
        # Win32 JOB_OBJECT_LIMIT_KILL_ON_JOB_CLOSE; only the final handle close kills the group.
        info.basic_limit_information.limit_flags = 0x00002000
        set_info = _windows_kernel32().SetInformationJobObject
        set_info.argtypes = [ctypes.c_void_p, ctypes.c_int, ctypes.c_void_p, ctypes.c_uint32]
        set_info.restype = ctypes.c_int
        return bool(set_info(
            ctypes.c_void_p(int(job_handle)), 9, ctypes.byref(info), ctypes.sizeof(info),
        ))
    except (AttributeError, OSError, TypeError, ValueError):
        return False


def duplicate_job_handle_to_process(job_handle: Any, pid: int) -> int | None:
    """Duplicate a Job handle into the gated worker before releasing the lab lock."""
    if os.name != "nt" or isinstance(pid, bool) or not isinstance(pid, int) or pid <= 0:
        return None
    kernel = _windows_kernel32()
    open_process = kernel.OpenProcess
    open_process.argtypes = [ctypes.c_uint32, ctypes.c_int, ctypes.c_uint32]
    open_process.restype = ctypes.c_void_p
    target_process = open_process(0x0040 | 0x1000, 0, pid)  # DUP_HANDLE | QUERY_LIMITED_INFORMATION
    if not target_process:
        return None
    try:
        get_current_process = kernel.GetCurrentProcess
        get_current_process.argtypes = []
        get_current_process.restype = ctypes.c_void_p
        duplicate = kernel.DuplicateHandle
        duplicate.argtypes = [
            ctypes.c_void_p, ctypes.c_void_p, ctypes.c_void_p,
            ctypes.POINTER(ctypes.c_void_p), ctypes.c_uint32, ctypes.c_int, ctypes.c_uint32,
        ]
        duplicate.restype = ctypes.c_int
        remote_handle = ctypes.c_void_p()
        if not duplicate(
            get_current_process(), ctypes.c_void_p(int(job_handle)), target_process,
            ctypes.byref(remote_handle), 0, 0, 0x00000002,  # DUPLICATE_SAME_ACCESS
        ):
            return None
        value = int(remote_handle.value or 0)
        return value or None
    finally:
        kernel.CloseHandle(target_process)


def _worker_job_handle_matches_current_process(job_handle: Any) -> bool:
    """Confirm that the persisted remote handle is open in this worker and covers it."""
    if os.name != "nt" or isinstance(job_handle, bool) or not isinstance(job_handle, int) or job_handle <= 0:
        return False
    try:
        kernel = _windows_kernel32()
        get_current_process = kernel.GetCurrentProcess
        get_current_process.argtypes = []
        get_current_process.restype = ctypes.c_void_p
        in_job = ctypes.c_int(0)
        is_in_job = kernel.IsProcessInJob
        is_in_job.argtypes = [ctypes.c_void_p, ctypes.c_void_p, ctypes.POINTER(ctypes.c_int)]
        is_in_job.restype = ctypes.c_int
        if not is_in_job(
            get_current_process(), ctypes.c_void_p(job_handle), ctypes.byref(in_job),
        ) or not in_job.value:
            return False
        return _windows_job_active_processes(job_handle=job_handle) is not None
    except (AttributeError, OSError, TypeError, ValueError):
        return False


def _terminate_windows_job_handle(job_handle: Any) -> bool:
    """Terminate only members of an already-open, operation-scoped Job Object."""
    if os.name != "nt" or not job_handle:
        return False
    try:
        terminate = _windows_kernel32().TerminateJobObject
        terminate.argtypes = [ctypes.c_void_p, ctypes.c_uint32]
        terminate.restype = ctypes.c_int
        return bool(terminate(ctypes.c_void_p(int(job_handle)), 1))
    except (AttributeError, OSError, TypeError, ValueError):
        return False


def resume_suspended_worker(process: Any) -> bool:
    """Resume a Windows worker only after its operation identity is durable."""
    if os.name != "nt":
        return True
    try:
        resume_process = ctypes.WinDLL("ntdll").NtResumeProcess
        resume_process.argtypes = [ctypes.c_void_p]
        resume_process.restype = ctypes.c_long
        return resume_process(ctypes.c_void_p(int(process._handle))) >= 0
    except (AttributeError, OSError, TypeError, ValueError):
        return False


def _open_windows_job_handle(identity: Any, access: int = 0x0004 | 0x0008) -> int | None:
    if os.name != "nt" or not isinstance(identity, dict):
        return None
    job_name = identity.get("job_name")
    if identity.get("kind") != "windows_job" or not isinstance(job_name, str):
        return None
    kernel = _windows_kernel32()
    open_job = kernel.OpenJobObjectW
    open_job.argtypes = [ctypes.c_uint32, ctypes.c_int, ctypes.c_wchar_p]
    open_job.restype = ctypes.c_void_p
    job = open_job(access, 0, job_name)
    return int(job) if job else None


def _windows_identity_action(
    pid: int, identity: dict[str, Any], *, terminate: bool, job_handle: Any = None,
) -> bool:
    if identity.get("kind") != "windows_job":
        return False
    owns_job = job_handle is None
    job = _open_windows_job_handle(identity) if owns_job else job_handle
    if not job:
        return False
    kernel = _windows_kernel32()
    open_process = kernel.OpenProcess
    open_process.argtypes = [ctypes.c_uint32, ctypes.c_int, ctypes.c_uint32]
    open_process.restype = ctypes.c_void_p
    process = open_process(0x1000, 0, pid)  # PROCESS_QUERY_LIMITED_INFORMATION
    if not process:
        if owns_job:
            kernel.CloseHandle(ctypes.c_void_p(int(job)))
        return False
    try:
        if _windows_start_token(process) != identity.get("start_token"):
            return False
        in_job = ctypes.c_int(0)
        is_in_job = kernel.IsProcessInJob
        is_in_job.argtypes = [ctypes.c_void_p, ctypes.c_void_p, ctypes.POINTER(ctypes.c_int)]
        is_in_job.restype = ctypes.c_int
        if not is_in_job(process, ctypes.c_void_p(int(job)), ctypes.byref(in_job)) or not in_job.value:
            return False
        if not terminate:
            return True
        return _terminate_windows_job_handle(job)
    finally:
        if owns_job:
            kernel.CloseHandle(ctypes.c_void_p(int(job)))
        kernel.CloseHandle(process)


def _windows_job_active_processes(
    identity: dict[str, Any] | None = None, *, job_handle: Any = None,
) -> int | None:
    """Return the active count, or None when the Job Object state is unknown."""
    class BasicAccounting(ctypes.Structure):
        _fields_ = [
            ("total_user_time", ctypes.c_int64), ("total_kernel_time", ctypes.c_int64),
            ("period_user_time", ctypes.c_int64), ("period_kernel_time", ctypes.c_int64),
            ("total_page_faults", ctypes.c_uint32), ("total_processes", ctypes.c_uint32),
            ("active_processes", ctypes.c_uint32), ("terminated_processes", ctypes.c_uint32),
        ]

    kernel = _windows_kernel32()
    owns_handle = job_handle is None
    if owns_handle:
        job_name = identity.get("job_name") if isinstance(identity, dict) else None
        if not isinstance(job_name, str):
            return None
        open_job = kernel.OpenJobObjectW
        open_job.argtypes = [ctypes.c_uint32, ctypes.c_int, ctypes.c_wchar_p]
        open_job.restype = ctypes.c_void_p
        job = open_job(0x0004, 0, job_name)  # JOB_OBJECT_QUERY
        if not job:
            # A missing object is not proof that its process tree has stopped.
            return None
    else:
        job = ctypes.c_void_p(int(job_handle))
    try:
        info = BasicAccounting()
        query = kernel.QueryInformationJobObject
        query.argtypes = [ctypes.c_void_p, ctypes.c_int, ctypes.c_void_p, ctypes.c_uint32,
                          ctypes.POINTER(ctypes.c_uint32)]
        query.restype = ctypes.c_int
        returned = ctypes.c_uint32(0)
        if not query(job, 1, ctypes.byref(info), ctypes.sizeof(info), ctypes.byref(returned)):
            return None
        return int(info.active_processes)
    finally:
        if owns_handle:
            kernel.CloseHandle(job)


def wait_for_job_empty(job_handle: Any, *, poll_seconds: float = 0.05) -> None:
    """Keep the owning handle alive until Windows proves the entire job is empty."""
    while True:
        if _windows_job_active_processes(job_handle=job_handle) == 0:
            return
        time.sleep(max(0.01, poll_seconds))


def wait_for_job_worker_only(job_handle: Any, *, poll_seconds: float = 0.05) -> None:
    """Keep the lab lock until only the worker itself remains in its Job Object."""
    while True:
        if _windows_job_active_processes(job_handle=job_handle) == 1:
            return
        time.sleep(max(0.01, poll_seconds))


def _worker_identity_matches(pid: int, identity: Any, *, job_handle: Any = None) -> bool:
    if not isinstance(identity, dict) or not isinstance(identity.get("start_token"), str):
        return False
    if identity.get("kind") == "linux_proc":
        details = _linux_process_details(pid)
        return bool(
            details
            and details[0] == identity["start_token"]
            and details[1] == identity.get("process_group") == pid
            and details[2] == identity.get("session_id") == pid
        )
    if identity.get("kind") == "posix_proc":
        return _pid_alive(pid) and identity.get("start_token") == str(pid)
    if os.name == "nt" and identity.get("kind") == "windows_job":
        return _windows_identity_action(pid, identity, terminate=False, job_handle=job_handle)
    return False


def _posix_group_alive(identity: Any) -> bool:
    if not isinstance(identity, dict) or identity.get("kind") != "posix_proc":
        return False
    pgid = identity.get("process_group")
    if isinstance(pgid, int) and pgid > 0:
        try:
            if hasattr(os, "killpg"):
                os.killpg(pgid, 0)
                return True
        except ProcessLookupError:
            return False
        except OSError:
            return True
    return False


def _linux_group_matches(identity: Any) -> bool | None:
    """Prove an isolated group still contains a process from its original session."""
    if not isinstance(identity, dict) or identity.get("kind") != "linux_proc":
        return False
    group = identity.get("process_group")
    session = identity.get("session_id")
    if (isinstance(group, bool) or not isinstance(group, int)
            or isinstance(session, bool) or not isinstance(session, int)):
        return False
    uncertain = False
    try:
        entries = list(os.scandir("/proc"))
    except OSError:
        return None
    for entry in entries:
        if not entry.name.isdigit():
            continue
        try:
            stat = Path(entry.path, "stat").read_text(encoding="ascii")
            fields = stat[stat.rfind(")") + 2:].split()
            if int(fields[2]) == group and int(fields[3]) == session:
                return True
        except (FileNotFoundError, ProcessLookupError):
            continue
        except PermissionError:
            uncertain = True
        except (OSError, IndexError, ValueError):
            uncertain = True
    return None if uncertain else False


def _worker_tree_stopped(pid: int, identity: Any, *, job_handle: Any = None) -> bool:
    if not isinstance(identity, dict):
        return False
    if identity.get("kind") == "linux_proc":
        return _linux_group_matches(identity) is False
    if identity.get("kind") == "posix_proc":
        return not _posix_group_alive(identity) and not _pid_alive(pid)
    if os.name == "nt" and identity.get("kind") == "windows_job":
        return _windows_job_active_processes(identity, job_handle=job_handle) == 0
    return False


def _terminate_worker_tree(
    pid: int, identity: dict[str, Any], *, force: bool = False, job_handle: Any = None,
) -> bool:
    if isinstance(pid, bool) or not isinstance(pid, int) or pid <= 0:
        raise ValueError("worker pid must be positive")
    if os.name == "nt":
        # Terminate the operation-scoped Job Object, never a PID-based taskkill tree.
        if _pid_alive(pid):
            return _windows_identity_action(pid, identity, terminate=True, job_handle=job_handle)
        return _terminate_windows_job_handle(job_handle) if job_handle else False
    if identity.get("kind") == "posix_proc":
        if _pid_alive(pid):
            if not _worker_identity_matches(pid, identity):
                return False
        elif not _posix_group_alive(identity):
            return False
        pgid = identity.get("process_group")
        if isinstance(pgid, int) and pgid > 0:
            try:
                sig = getattr(signal, "SIGKILL", 9) if force else signal.SIGTERM
                if hasattr(os, "killpg"):
                    os.killpg(pgid, sig)
                else:
                    os.kill(pid, sig)
            except ProcessLookupError:
                return True
            except OSError:
                return False
            return True
        return False
    if identity.get("kind") != "linux_proc":
        return False
    if _pid_alive(pid):
        if not _worker_identity_matches(pid, identity):
            return False
    elif _linux_group_matches(identity) is not True:
        return False
    try:
        os.killpg(identity["process_group"], signal.SIGKILL if force else signal.SIGTERM)
    except ProcessLookupError:
        return True
    except OSError:
        return False
    return True


def _wait_worker_exit(
    pid: int, timeout: float = 10.0, identity: Any = None, *, job_handle: Any = None,
) -> bool:
    deadline = time.monotonic() + max(0.0, timeout)
    while time.monotonic() < deadline:
        if _worker_tree_stopped(pid, identity, job_handle=job_handle):
            return True
        if isinstance(identity, dict) and identity.get("kind") == "windows_job" and job_handle:
            time.sleep(0.05)
            continue
        if not _worker_identity_matches(pid, identity) and not (
            identity.get("kind") == "linux_proc" and _linux_group_matches(identity) is True
        ) and not (
            identity.get("kind") == "posix_proc" and _posix_group_alive(identity)
        ):
            return False
        time.sleep(0.05)
    if _worker_tree_stopped(pid, identity, job_handle=job_handle):
        return True
    if isinstance(identity, dict) and identity.get("kind") == "windows_job" and job_handle:
        if not _terminate_windows_job_handle(job_handle):
            return False
        deadline = time.monotonic() + 2.0
        while time.monotonic() < deadline:
            if _worker_tree_stopped(pid, identity, job_handle=job_handle):
                return True
            time.sleep(0.05)
        return _worker_tree_stopped(pid, identity, job_handle=job_handle)
    if _worker_identity_matches(pid, identity) or (
        identity.get("kind") == "linux_proc" and _linux_group_matches(identity) is True
    ) or (
        identity.get("kind") == "posix_proc" and _posix_group_alive(identity)
    ):
        if not _terminate_worker_tree(pid, identity, force=True):
            return False
        deadline = time.monotonic() + 2.0
        while time.monotonic() < deadline:
            if _worker_tree_stopped(pid, identity):
                return True
            if not _worker_identity_matches(pid, identity) and not (
                identity.get("kind") == "linux_proc" and _linux_group_matches(identity) is True
            ) and not (
                identity.get("kind") == "posix_proc" and _posix_group_alive(identity)
            ):
                return False
            time.sleep(0.05)
    return _worker_tree_stopped(pid, identity)


def _cancel_terminal(store: SQLiteStore, operation: dict[str, Any]) -> dict[str, Any]:
    status = operation["status"]
    if status not in {"queued", "running"}:
        return operation
    store.transition_operation(
        operation["operation_id"], status, "failed",
        error={"code": "operation_cancelled", "message": "Operation cancelled by request"},
    )
    return store.get_operation(operation["operation_id"])


def _recover_cancelled_lab(config: LabConfig, kind: str, operation_id: str) -> list[str]:
    from .trial import recover_lab

    interrupted = recover_lab(config, restore_candidate=True)
    if interrupted and config.storage_mode == "sqlite":
        store = SQLiteStore()
        for run_ref in interrupted:
            manifest = store.load_manifest(config.lab_id, run_ref)
            if isinstance(manifest, dict) and manifest.get("status") == "interrupted":
                manifest["reason"] = "Operation cancelled by request"
                manifest["cancelled_operation_id"] = str(operation_id)
                store.save_manifest(config.lab_id, run_ref, manifest)
    if kind in {"trial", "resume"} and not interrupted:
        state = SQLiteStore().load_state(config.lab_id)
        best_commit = state.get("best_commit")
        if isinstance(best_commit, str) and best_commit:
            from .gitutil import _restore_candidate
            _restore_candidate(config, best_commit)
    return interrupted


def cancel_run(
    lab_id: str,
    run_ref: str,
    *,
    expected_operation_id: str | None = None,
    timeout: float = 10.0,
) -> dict[str, Any]:
    """Cancel the active lab operation associated with a nonterminal run."""
    store = SQLiteStore()
    run_id = store.resolve_run_id(lab_id, run_ref)
    run = store.get_run(lab_id, run_id)
    manifest = run.get("manifest") if run else None
    if isinstance(manifest, dict) and manifest.get("status") == "interrupted":
        cancelled_operation_id = manifest.get("cancelled_operation_id")
        if isinstance(cancelled_operation_id, str):
            cancelled = store.get_operation(cancelled_operation_id)
            error = cancelled.get("error")
            if (cancelled.get("status") == "failed" and isinstance(error, dict)
                    and error.get("code") == "operation_cancelled"):
                if expected_operation_id and str(cancelled_operation_id) != str(expected_operation_id):
                    raise LabError("The supplied operation does not own this run", code="operation_run_mismatch")
                return cancelled
    if not run or run.get("status") not in {"created", "queued", "running"}:
        raise LabError("Run is not active and cannot be cancelled", code="operation_not_cancellable")
    operation = store.get_active_operation(lab_id)
    if not operation:
        raise LabError("No active operation owns this run", code="operation_not_cancellable")
    if operation.get("status") not in {"queued", "running"}:
        raise LabError("The operation is no longer cancellable", code="operation_not_cancellable")
    params = operation.get("payload", {}).get("params", {})
    bound_run_ref = params.get("run_id") if isinstance(params, dict) else None
    if isinstance(bound_run_ref, str):
        try:
            bound_run_id = store.resolve_run_id(lab_id, bound_run_ref)
        except EntityNotFoundError as error:
            raise LabError("Active operation references a different run", code="operation_run_mismatch") from error
        if bound_run_id != run_id:
            raise LabError("Active operation is bound to a different run", code="operation_run_mismatch")
    if expected_operation_id and str(operation["operation_id"]) != str(expected_operation_id):
        raise LabError("The supplied operation does not own this run", code="operation_run_mismatch")
    if operation["kind"] not in {run.get("kind"), "resume", "recover"}:
        raise LabError("Active operation does not match this run", code="operation_run_mismatch")
    cancelled = cancel_operation(str(operation["operation_id"]), timeout=timeout)
    error = cancelled.get("error")
    if cancelled.get("status") in {"succeeded", "failed"} and not (
        isinstance(error, dict) and error.get("code") == "operation_cancelled"
    ):
        raise LabError("Run completed before cancellation could be applied", code="operation_not_cancellable")
    return cancelled


def cancel_operation(operation_id: str, *, timeout: float = 10.0) -> dict[str, Any]:
    """Persist cancellation, stop the worker tree, then recover under the lab lock."""
    store = SQLiteStore()
    operation = store.get_operation(operation_id)
    if operation["status"] in {"succeeded", "failed"}:
        return operation
    if operation["status"] not in {"queued", "running"}:
        raise LabError("Operation cannot be cancelled after finalization or uncertain recovery", code="operation_not_cancellable")
    config = _config_for(str(operation["lab_id"]))
    operation = store.request_operation_cancel(operation_id)
    pid = int(operation.get("pid") or 0)
    if not pid:
        # Serialize the no-worker case with the launcher, which records its child under this lock.
        with lab_lock(config.state_dir):
            current = store.get_operation(operation_id)
            if current["status"] in {"succeeded", "failed"}:
                return current
            pid = int(current.get("pid") or 0)
            if not pid and current["status"] == "queued":
                _recover_cancelled_lab(config, current["kind"], str(current["operation_id"]))
                return _cancel_terminal(store, current)
        if not pid:
            return store.set_operation_cancel_pending(operation_id, "worker_identity_unavailable")
        operation = store.get_operation(operation_id)
    progress = operation.get("progress")
    identity = progress.get("worker_identity") if isinstance(progress, dict) else None
    if not isinstance(identity, dict):
        return store.set_operation_cancel_pending(operation_id, "worker_identity_unavailable")

    # Keep this caller-owned handle open through termination and the empty-tree proof.
    # Otherwise the worker's exit can close the last handle before we can verify its job.
    job_handle = None
    if os.name == "nt" and identity.get("kind") == "windows_job":
        job_handle = _open_windows_job_handle(identity)
        if not job_handle:
            return store.set_operation_cancel_pending(operation_id, "worker_tree_unavailable")
    try:
        if _pid_alive(pid):
            if not _worker_identity_matches(pid, identity, job_handle=job_handle):
                return store.set_operation_cancel_pending(operation_id, "worker_identity_mismatch")
            if not _terminate_worker_tree(pid, identity, job_handle=job_handle):
                return store.set_operation_cancel_pending(operation_id, "worker_tree_unavailable")
        elif not _worker_tree_stopped(pid, identity, job_handle=job_handle):
            if identity.get("kind") == "linux_proc" and _linux_group_matches(identity) is True:
                if not _terminate_worker_tree(pid, identity):
                    return store.set_operation_cancel_pending(operation_id, "worker_tree_unavailable")
            elif identity.get("kind") == "posix_proc":
                if not _terminate_worker_tree(pid, identity):
                    return store.set_operation_cancel_pending(operation_id, "worker_tree_unavailable")
            elif identity.get("kind") == "windows_job":
                active = _windows_job_active_processes(identity, job_handle=job_handle)
                if active is None:
                    return store.set_operation_cancel_pending(operation_id, "worker_tree_unavailable")
                if active > 0 and not _terminate_worker_tree(pid, identity, job_handle=job_handle):
                    return store.set_operation_cancel_pending(operation_id, "worker_tree_unavailable")
            else:
                return store.set_operation_cancel_pending(operation_id, "worker_identity_mismatch")
        if not _wait_worker_exit(pid, timeout, identity, job_handle=job_handle):
            return store.set_operation_cancel_pending(operation_id, "worker_exit_unconfirmed")

        with lab_lock(config.state_dir):
            current = store.get_operation(operation_id)
            if current["status"] in {"succeeded", "failed"}:
                return current
            if current["status"] not in {"queued", "running"}:
                raise LabError("Operation entered an uncertain state while cancellation was pending",
                               code="operation_not_cancellable")
            progress = current.get("progress")
            if not isinstance(progress, dict) or progress.get("cancel_requested") is not True:
                raise LabError("Durable cancel request was not recorded", code="operation_state_conflict")
            _recover_cancelled_lab(config, current["kind"], str(current["operation_id"]))
            return _cancel_terminal(store, current)
    finally:
        close_worker_identity_resource(job_handle)
